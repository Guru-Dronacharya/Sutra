def test_req_5_1_policy_extractor():
    """REQ-5.1: Verify policy extractor parses sections and tracks section locations."""
    extractor = PolicyExtractor()
    doc_text = """
# SECTION 1: Consent Management
Explicit consent must be recorded.

# SECTION 2: Data Retention
Data is retained for 180 days only.
"""
    sections = extractor.extract_from_text(doc_text, "test_policy.md")
    assert len(sections) == 2
    assert "Consent Management" in sections[0]["section_title"]
    assert "Section 1" in sections[0]["location"]
    assert "Data Retention" in sections[1]["section_title"]


def test_req_5_3_offline_judge_covered_and_gap():
    """REQ-5.3: Verify OfflineJudge accurately assigns Covered vs Gap status with evidence excerpts."""
    judge = OfflineJudge()
    policy_sections = [
        {
            "section_title": "Security and Breach Reporting",
            "content": "In the event of an identified personal data breach, an initial notice shall be transmitted to the Data Protection Board within 72 hours of discovery.",
            "location": "Section 2: Breach Protocol",
        }
    ]

    # Test 1: Obligation on 72-hour breach notification -> COVERED
    ob_covered = {
        "instrument": "DPDP Rules 2025",
        "section_id": "RULE 7",
        "text": "[RULE 7] Data Breach Notification within 72 hours to Data Protection Board.",
    }
    res_covered = judge.evaluate(ob_covered, policy_sections)
    assert res_covered["status"] in [FindingStatus.COVERED, FindingStatus.PARTIALLY_COVERED]
    assert res_covered["evidence_excerpt"] is not None
    assert "72 hours" in res_covered["evidence_excerpt"]

    # Test 2: Obligation on Children Data (omitted from policy) -> GAP
    ob_gap = {
        "instrument": "DPDP Act 2023",
        "section_id": "SECTION 9",
        "text": "[SECTION 9] Verifiable parental consent and absolute prohibition on behavioral tracking of children.",
    }
    res_gap = judge.evaluate(ob_gap, policy_sections)
    assert res_gap["status"] == FindingStatus.GAP
    assert res_gap["evidence_excerpt"] is None
    assert "Compliance Gap" in res_gap["remediation_note"]


def test_req_5_2_tier_filtered_gap_analysis(setup_gap_fixture):
    """REQ-5.2: Verify gap analysis evaluates only obligations applicable to model's tier and exposure profile."""
    db = SyncSessionLocal()
    engine = GapAnalysisEngine()
    fixture = setup_gap_fixture

    # Run 1: High Tier Model with India Only
    rep_high = engine.run_gap_analysis(
        db=db,
        model_id=fixture["m_high_id"],
        policy_document_id=fixture["policy_id"],
        exposure_profile=ExposureProfile.INDIA_ONLY,
    )
    assert rep_high.id is not None
    assert rep_high.tier == RiskTier.HIGH
    assert rep_high.summary["total_obligations"] > 0
    assert "coverage_percentage" in rep_high.summary

    # Ensure no EU AI Act obligations evaluated under India-only profile
    findings_high = db.query(Finding).filter(Finding.report_id == rep_high.id).all()
    assert all("European Union" not in f.cited_instrument for f in findings_high)

    # Run 2: High Tier Model with India + EU Exposure
    rep_eu = engine.run_gap_analysis(
        db=db,
        model_id=fixture["m_high_id"],
        policy_document_id=fixture["policy_id"],
        exposure_profile=ExposureProfile.INDIA_PLUS_EU,
    )
    findings_eu = db.query(Finding).filter(Finding.report_id == rep_eu.id).all()
    eu_found = any("European Union" in f.cited_instrument for f in findings_eu)
    assert eu_found is True, "EU exposure profile must include EU AI Act obligations"
    db.close()


def test_req_5_4_findings_remediation_citations(setup_gap_fixture):
    """REQ-5.4: Verify findings cite statutory instruments, section numbers, and concrete remediation notes."""
    db = SyncSessionLocal()
    rep = db.query(GapReport).order_by(GapReport.created_at.desc()).first()
    assert rep is not None

    findings = db.query(Finding).filter(Finding.report_id == rep.id).all()
    assert len(findings) > 0

    for f in findings:
        assert f.cited_instrument != ""
        assert f.cited_section != ""
        assert f.status in [FindingStatus.COVERED, FindingStatus.PARTIALLY_COVERED, FindingStatus.GAP]
        assert f.remediation_note != ""
        assert f.confidence > 0.0

    db.close()


